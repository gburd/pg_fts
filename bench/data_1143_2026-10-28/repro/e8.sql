SET client_min_messages = warning;
CREATE EXTENSION IF NOT EXISTS pg_fts;
CREATE TABLE r (id int PRIMARY KEY, live bool NOT NULL DEFAULT true, body text) WITH (autovacuum_enabled = off);
INSERT INTO r (id, body) SELECT g, 'common common filler' || g FROM generate_series(1, 1000) g;
INSERT INTO r (id, body) VALUES (5000, 'rare filler');
CREATE INDEX r_fts ON r USING fts (to_ftsdoc('simple', body)) WHERE live;
ANALYZE r;
\set top3 'SELECT id FROM r WHERE live AND to_ftsdoc(''simple'', body) @@@ to_ftsquery(''simple'', ''common | rare'') ORDER BY to_ftsdoc(''simple'', body) <=> to_ftsquery(''simple'', ''common | rare'') LIMIT 3'
EXPLAIN :top3;
:top3;
SET enable_bitmapscan = off; SET enable_seqscan = off;
EXPLAIN :top3;
:top3;
RESET enable_bitmapscan; RESET enable_seqscan;
CREATE TABLE pn (id int, d ftsdoc) WITH (autovacuum_enabled = off);
INSERT INTO pn SELECT g, to_ftsdoc('simple', 'alpha w' || (g % 10)) FROM generate_series(1, 2000) g;
CREATE INDEX pn_fts ON pn USING fts (d) WHERE id <= 100;
VACUUM ANALYZE pn;
EXPLAIN SELECT 1 FROM pn WHERE id <= 100 AND d @@@ 'alpha'::ftsquery;
EXPLAIN SELECT 1 FROM pn WHERE id <= 50 AND d @@@ 'alpha'::ftsquery;
EXPLAIN SELECT 1 FROM pn WHERE id <= 100 AND d @@@ 'w3'::ftsquery;
EXPLAIN SELECT 1 FROM pn WHERE d @@@ 'alpha'::ftsquery;
CREATE INDEX pn_full ON pn USING fts (d);
INSERT INTO pn SELECT g, to_ftsdoc('simple', 'beta') FROM generate_series(2001, 2400) g;
SELECT fts_merge('pn_full');
ANALYZE pn;
EXPLAIN SELECT 1 FROM pn WHERE id <= 100 AND d @@@ 'beta'::ftsquery;
DROP INDEX pn_full;
EXPLAIN SELECT 1 FROM pn WHERE id <= 100 AND d @@@ 'beta'::ftsquery;
